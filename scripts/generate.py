"""
Rebuilds the generated parts of momenta from the figure sources:
  - packages/momenta/src/react/index.ts        React component per figure
  - apps/site/src/data/catalog.ts               gallery shelves, use lines, progress and count flags
  - packages/momenta/test/lists.ts              which figures show progress and accept a count

Run from the repository root:  python3 scripts/generate.py
Figures are found by their `export const name = defineFigure(...)` line; the `/** ... */` comment
directly above it supplies the gallery's use line ("Use for ..."), and `ctx.count(` / `ctx.progress(` /
`ctx.determinate` in a figure's body decide its flags.
"""
import glob, json, re, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "packages/momenta/src/figures")
ORDER = ["creators", "files", "communication", "commerce", "account", "ai", "media",
         "security", "productivity", "devices", "wellness", "travel", "system"]
TITLE = {"files": "Files", "communication": "Communication", "commerce": "Commerce", "account": "Account",
         "ai": "AI and data", "system": "System", "creators": "Creators", "media": "Media",
         "security": "Security", "productivity": "Productivity", "devices": "Devices",
         "wellness": "Wellness", "travel": "Travel"}


def scan():
    figs = {}
    for path in sorted(glob.glob(os.path.join(SRC, "**/*.ts"), recursive=True)):
        if path.endswith(("shapes.ts", "index.ts")):
            continue
        s = open(path, encoding="utf-8").read()
        shelf = os.path.relpath(path, SRC).split(os.sep)[0]
        for m in re.finditer(r"(?:/\*\* (.+?) \*/\s*)?export const (\w+) = defineFigure", s):
            rest = s[m.end():]
            nxt = re.search(r"\n(?:/\*\*[^\n]*\*/\n)?export const \w+ = defineFigure", rest)
            body = rest[: nxt.start()] if nxt else rest
            label = re.search(r'label: "([^"]+)"', body)
            figs[m.group(2)] = {
                "shelf": shelf,
                "doc": m.group(1) or "",
                "label": label.group(1) if label else m.group(2),
                "progress": "ctx.progress(" in body or "ctx.determinate" in body,
                "count": "ctx.count(" in body,
            }
    return figs


def use_line(doc, label):
    m = re.search(r"Use for ([^.`]+?)(?:\.|`|$)", doc)
    if m:
        t = m.group(1).strip()
        return t[0].upper() + t[1:]
    return doc.split(".")[0] or label


