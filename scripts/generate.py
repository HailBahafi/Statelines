def main():
    figs = scan()
    # React exports
    react = ['import * as figures from "../figures";', 'import { createComponent } from "./create-component";', "",
             'export { createComponent, type FigureComponent, type FigureProps } from "./create-component";', ""]
    for name in figs:
        react.append(f"export const {name[0].upper() + name[1:]} = createComponent(figures.{name});")
    open(os.path.join(ROOT, "packages/momenta/src/react/index.ts"), "w").write("\n".join(react) + "\n")

    # Catalog
    lines = ['// Generated by scripts/generate.py. Do not edit by hand.',
             'import * as figures from "momenta";',
             'import type { Figure } from "momenta";', "",
             "export interface Entry {", '  key: keyof typeof figures & string;', "  figure: Figure<any>;", "  use: string;",
             "  /** Shows real progress during loading. */", "  progress: boolean;",
             "  /** The range `count` accepts, when the figure has countable items. */", "  count?: readonly [number, number];", "}", "",
             "export interface Shelf {", "  id: string;", "  title: string;", "  entries: Entry[];", "}", "",
             "const entry = (key: Entry[\"key\"], use: string, progress: boolean, count?: readonly [number, number]): Entry =>",
             "  ({ key, figure: figures[key] as Figure<any>, use, progress, count });", "",
             "export const catalog: Shelf[] = ["]
    for shelf in ORDER:
        names = [n for n, v in figs.items() if v["shelf"] == shelf]
        lines += ["  {", f'    id: "{shelf}", title: "{TITLE[shelf]}", entries: [']
        for n in names:
            v = figs[n]
            use = use_line(v["doc"], v["label"]).replace('"', '\\"')
            rng = f", [{COUNT[n][0]}, {COUNT[n][1]}]" if n in COUNT else ""
            lines.append(f'      entry("{n}", "{use}", {"true" if v["progress"] else "false"}{rng}),')
        lines.append("    ] },")
    lines.append("];")
    open(os.path.join(ROOT, "apps/site/src/data/catalog.ts"), "w").write("\n".join(lines) + "\n")

    # Test lists
    prog = sorted(n for n, v in figs.items() if v["progress"])
    cnt = sorted(n for n, v in figs.items() if v["count"])
    open(os.path.join(ROOT, "packages/momenta/test/lists.ts"), "w").write(
        "/** Generated by scripts/generate.py from the figure sources. */\n"
        f"export const PROGRESS = {json.dumps(prog)} as const;\n"
        f"export const COUNT = {json.dumps(cnt)} as const;\n")
    print(f"{len(figs)} figures; progress {len(prog)}; count {len(cnt)}; shelves "
          + ", ".join(f"{s} {sum(1 for v in figs.values() if v['shelf'] == s)}" for s in ORDER))


if __name__ == "__main__":
    main()
